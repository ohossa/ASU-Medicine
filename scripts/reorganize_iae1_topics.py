def apply():
    data = json.loads(BANK_PATH.read_text(encoding='utf-8'))
    assert len(data['chapters']) == len(chapters_spec)

    total_processed = 0
    for idx, ch in enumerate(data['chapters']):
        spec = chapters_spec[idx]
        s = ch['subjects'][0]
        qs = s['questions']
        new_topics = spec['topics']
        mapping = spec['map']
        
        # Update subject metadata
        s['lectureNames'] = new_topics
        s['lectureCount'] = len(new_topics)
        s['lectures'] = ', '.join(new_topics)
        ch['lectureRange'] = f'Topics 1–{len(new_topics)}'
        
        for q in qs:
            old_l = q['lecture']
            new_topic = mapping[old_l]
            new_l = new_topics.index(new_topic) + 1
            q['lecture'] = new_l
            q['contentVersion'] = digest(content(q))
            total_processed += 1

    assert total_processed == 1013, f'Expected 1013 questions, got {total_processed}'
    
    # Write back formatted JSON with 2-space indentation and newline
    BANK_PATH.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    print(f'Successfully updated {BANK_PATH} with {total_processed} questions across 56 consolidated topics.')

if __name__ == '__main__':
    apply()
